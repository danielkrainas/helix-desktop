#!/usr/bin/env python3
"""List the files with translatable text, one per line, as po/POTFILES
holds them: Rust sources that call the i18n functions with a literal,
then the session's desktop file and the polkit policies.

    python3 tools/i18n/potfiles.py > po/POTFILES

The rule for Rust sources is the same as the unit test that checks
po/POTFILES (crates/helix-i18n/tests/potfiles.rs).
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CALL = re.compile(r'(?<![A-Za-z0-9_])(tr|trc|trn|n_)\(\s*"|(?<![A-Za-z0-9_])trn?f!\(')
# Not shown to people: examples and test helpers.
SKIP_DIRS = ("tests", "target", "examples", "helix-test-support")


def rust_files():
    out = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "crates")):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            if f.endswith(".rs"):
                p = os.path.join(dirpath, f)
                rel = os.path.relpath(p, ROOT)
                if CALL.search(open(p, encoding="utf-8").read()):
                    out.append(rel)
    return sorted(out)


def data_files():
    policies = sorted(f for f in os.listdir(os.path.join(ROOT, "data")) if f.endswith(".policy"))
    return ["session/helix.desktop"] + ["data/" + f for f in policies]


def main():
    sys.stdout.write("# Generated by tools/i18n/potfiles.py; do not edit.\n")
    for f in rust_files() + data_files():
        sys.stdout.write(f + "\n")


if __name__ == "__main__":
    main()
